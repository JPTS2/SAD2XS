########################################
# Make SAD
########################################
def make_sad(
        config:         InstallConfig,
        env:            dict[str, str],
        reused_tree:    bool,
        work_dir:       Path) -> None:
    """
    Run SAD's build steps against a prepared environment.

    Parameters
    ----------
    config : InstallConfig
        Install configuration.
    env : dict
        Environment variables for the build.
    reused_tree : bool
        Whether an existing tree is being reused, as `prepare_source`
        returns.
    work_dir : Path
        Directory to build in.

    Raises
    ------
    CommandError
        If a build step returns non-zero.
    """
    # Only meaningful on a reused tree; a fresh clone has nothing to clean,
    # and upstream's clean target returns non-zero when there is not.
    if reused_tree:
        run(
            ["make", "clean"],
            cwd             = work_dir,
            env             = env,
            log_path        = config.build_log,
            stdin_devnull   = True,
            check           = False)

    for target in ("depend", "exe"):
        run(
            ["make", target],
            cwd             = work_dir,
            env             = env,
            log_path        = config.build_log,
            stdin_devnull   = True)

########################################
# Verify Executable
########################################
def verify_executable(
        config:     InstallConfig,
        work_dir:   Path) -> None:
    """
    Check that the build produced a runnable SAD binary.

    Parameters
    ----------
    config : InstallConfig
        Install configuration.
    work_dir : Path
        Directory the build ran in.

    Raises
    ------
    SystemExit
        If the binary is missing or not executable.
    """
    executable = work_dir / "bin" / "gs"
    if not os.access(executable, os.X_OK):
        sys.exit(
            f"Build finished but {executable} is missing or not "
            f"executable. See {config.build_log}")
    logger.info(f"Build OK: {executable}")

################################################################################
# Source Lifecycle
################################################################################
def install_sad_source(
        config:     InstallConfig,
        env:        dict[str, str],
        prepare:    Callable[[Path], None] | None = None) -> None:
    """
    Install SAD as one transaction: source, build, and launcher together.

    Anything already at the launcher path is checked before a single file
    moves, so an unowned launcher costs no clone and no build. Any previous
    source tree is then held aside for the whole clone, preparation, build,
    and launcher write, and put back if any of them fails.

    `--reuse-clone` rebuilds in place, as it asks, and has no previous tree
    to fall back to.

    Parameters
    ----------
    config : InstallConfig
        Install configuration.
    env : dict
        Environment variables for the build.
    prepare : callable, optional
        Platform-specific preparation, called with the source directory.
        Defaults to None.

    Raises
    ------
    SystemExit
        If the launcher path is occupied, the source cannot be had, or the
        build produced no executable.
    CommandError
        If a build step returns non-zero.
    RollbackError
        If a failure could not be undone. The preserved transaction and
        any previous source location are reported.

    Notes
    -----
    The launcher needs no rollback of its own. It is only replaced once it
    has been shown to be this installer's, the replacement is staged beside
    it and swapped in one step, and it always names the fixed source path,
    so restoring an earlier tree leaves it pointing at the right place.
    """
    ########################################
    # Preflight
    ########################################
    # Both run before anything moves: an unfinished install from an earlier
    # run, or an unowned launcher, must not cost a clone and a build.
    reconcile_transaction(config)
    _launcher_is_replaceable(config.launcher)

    reused_tree = prepare_source(config)

    try:
        if prepare is not None:
            prepare(config.src_dir)
        make_sad(config, env, reused_tree, config.src_dir)
        verify_executable(config, config.src_dir)
        write_launcher(config)
    except BaseException as error:
        rollback(config, error)
        raise

    _retire_transaction(config)

