# Launcher
################################################################################
########################################
# Ownership Check
########################################
def _launcher_is_replaceable(launcher: Path) -> None:
    """
    Refuse to replace anything this installer did not write.

    The marker has to be one of the file's own lines. Matching it anywhere
    in the text would accept any script that merely mentions it.

    Parameters
    ----------
    launcher : Path
        The path the launcher would be written to.

    Raises
    ------
    SystemExit
        If something occupies the path that carries no marker.
    """
    # lstat, not exists: a symlink to a missing target still occupies the
    # name, and following it would write through to wherever it points.
    try:
        status = launcher.lstat()
    except FileNotFoundError:
        return

    if stat.S_ISLNK(status.st_mode):
        sys.exit(
            f"{launcher} is a symlink, so it was not written by this "
            f"installer. Remove it yourself, or choose another --bin-dir.")

    if not stat.S_ISREG(status.st_mode):
        sys.exit(
            f"{launcher} is not a regular file. Remove it yourself, or "
            f"choose another --bin-dir.")

    try:
        existing = launcher.read_text(encoding = "utf-8", errors = "replace")
    except OSError as error:
        sys.exit(f"Could not read {launcher}: {error}")

    if LAUNCHER_MARKER not in existing.splitlines():
        sys.exit(
            f"{launcher} already exists and was not written by this "
            f"installer. Remove it yourself, or choose another --bin-dir.")

########################################
# Launcher Text
########################################
def _launcher_text(src_dir: Path) -> str:
    """
    Build the launcher script for a source tree.

    Parameters
    ----------
    src_dir : Path
        The SAD source tree the launcher runs.

    Returns
    -------
    str
        The launcher script.

    Notes
    -----
    1) Called with a file, the launcher runs in batch mode from the caller's
       working directory
    2) Called with no arguments, it runs interactively from the source
       directory, which is where SAD looks for its own support files
    """
    # shlex.quote: the prefix is user-supplied and lands inside shell source,
    # where a quote or $( ) would break the script or be evaluated.
    quoted = shlex.quote(str(src_dir))

    # python3 rather than realpath(1), which older macOS does not ship.
    return f"""#!/usr/bin/env bash
{LAUNCHER_MARKER}
set -e
SAD_DIR={quoted}
GS_EXEC="$SAD_DIR/bin/gs"
CALL_DIR="$(pwd)"

if [[ $# -gt 0 ]]; then
    if [[ "$1" = /* ]]; then
        SAD_INPUT="$1"
    else
        SAD_INPUT="$(python3 -c 'import os,sys; print(os.path.realpath(sys.argv[1]))' "$CALL_DIR/$1")"
    fi
    shift
    cd "$CALL_DIR" || exit 1
    exec "$GS_EXEC" "$SAD_INPUT" "$@"
else
    cd "$SAD_DIR" || exit 1
    exec "$GS_EXEC"
fi
"""

########################################
# Launcher Installation
########################################
def write_launcher(config: InstallConfig) -> None:
    """
    Write the `sad` launcher script.

    Anything already at the path is inspected first, without following a
    symlink, and only a launcher this installer wrote is replaced. The
    replacement is staged beside it and swapped in one step, so an
    interrupted write cannot leave a half-written script on PATH.

    Parameters
    ----------
    config : InstallConfig
        Install configuration.

    Raises
    ------
    SystemExit
        If the path is occupied by something this installer did not write.
    """
    _launcher_is_replaceable(config.launcher)

    config.bin_dir.mkdir(parents = True, exist_ok = True)

    handle, staging_name = tempfile.mkstemp(
        dir     = config.bin_dir,
        prefix  = ".sad-staging-")
    staging = Path(staging_name)
    try:
        with os.fdopen(handle, "w", encoding = "utf-8") as staged:
            staged.write(_launcher_text(config.src_dir))
        staging.chmod(0o755)
        os.replace(staging, config.launcher)
    except BaseException:
        staging.unlink(missing_ok = True)
        raise

    logger.info(f"Launcher written: {config.launcher}")

################################################################################
# PATH Reporting
################################################################################
def report_path_setup(config: InstallConfig) -> None:
    """
    Report whether the launcher directory is reachable from the shell.

    Shell configuration is never modified. Editing a user's rc file is
    invasive, and a throwaway `--bin-dir` would leave a permanent entry
    behind pointing at a directory that need not outlive the shell.

    Parameters
    ----------
    config : InstallConfig
        Install configuration.
    """
    bin_dir = str(config.bin_dir)

    # Membership of bin_dir in PATH is not enough: an earlier entry can carry
    # its own sad, and that is the one the shell would run.
    found = shutil.which("sad")
    if found is not None and Path(found).resolve() == config.launcher.resolve():
        logger.info(f"sad resolves to {config.launcher}")
        return

    # Quoted because these lines are meant to be pasted into a shell, and the
    # directory came from --bin-dir.
    if bin_dir not in os.environ.get("PATH", "").split(os.pathsep):
        logger.warning(f"{bin_dir} is not on PATH")
        logger.info(
            f"Add it by appending this line to your shell configuration:\n"
            f'  export PATH={shlex.quote(bin_dir)}:"$PATH"')
        return

    if found is None:
        logger.warning(f"{bin_dir} is on PATH but sad does not resolve from it")
    else:
        logger.warning(f"sad resolves to {found}, not the launcher just written")
    logger.info(
        f"Put {bin_dir} first so the new launcher wins:\n"
        f'  export PATH={shlex.quote(bin_dir)}:"$PATH"')
