########################################
# Checkout Inspection
########################################
def _git_value(src_dir: Path, *args: str) -> str | None:
    """
    Read one value out of a git checkout, or None if it cannot be read.

    Parameters
    ----------
    src_dir : Path
        Directory to inspect.
    *args : str
        Arguments following `git -C <src_dir>`.

    Returns
    -------
    str or None
        The trimmed output, or None if the directory is not a checkout or
        git reported an error.
    """
    if not (src_dir / ".git").is_dir():
        return None

    process = subprocess.run(           # pylint: disable=subprocess-run-check
        ["git", "-C", str(src_dir), *args],
        text    = True,
        stdout  = subprocess.PIPE,
        stderr  = subprocess.DEVNULL)
    if process.returncode != 0:
        return None
    return process.stdout.strip()


def _installer_owns_tree(config: InstallConfig) -> bool:
    """
    Return True if the existing source tree is this installer's to replace.

    The marker is the only proof accepted. A matching git origin is not
    enough: a user's own SAD checkout would then be deleted by a reinstall
    that happened to point at the same directory.

    Parameters
    ----------
    config : InstallConfig
        Install configuration.

    Returns
    -------
    bool
        True if the tree may be removed.
    """
    return _tree_is_owned(config.src_dir)

########################################
# Prefix Guard
########################################
def _guard_prefix(config: InstallConfig) -> None:
    """
    Refuse a prefix that cannot be safely written to.

    Parameters
    ----------
    config : InstallConfig
        Install configuration.

    Raises
    ------
    SystemExit
        If the prefix is the user's home directory or a filesystem root.
    """
    # Both sides resolved: where home is reached through a symlink, as on
    # AFS, comparing a resolved prefix to an unresolved home fails open.
    resolved = config.prefix
    if resolved == Path.home().resolve() or resolved == resolved.parent:
        sys.exit(
            f"Refusing to install into {resolved}. Choose a dedicated "
            f"directory, such as {default_prefix()}.")

########################################
# Source Selection
########################################
def _resolve_branch(config: InstallConfig) -> str | None:
    """
    Return the branch to clone, or None to take the remote's default.

    Parameters
    ----------
    config : InstallConfig
        Install configuration.

    Returns
    -------
    str or None
        The branch name, or None when the remote default should be used.

    Raises
    ------
    SystemExit
        If a branch the user asked for by name is absent on the remote. A
        typo would otherwise install unintended source and report success.
    """
    try:
        process = subprocess.run(       # pylint: disable=subprocess-run-check
            ["git", "ls-remote", "--exit-code", "--heads",
             config.repo_url, config.branch],
            text    = True,
            stdout  = subprocess.DEVNULL,
            stderr  = subprocess.PIPE)
    except OSError as error:
        sys.exit(f"Could not run git to query {config.repo_url}: {error}")

    if process.returncode == 0:
        return config.branch

    # git ls-remote --exit-code returns 2 for "queried fine, no such head".
    # Anything else is the remote or the network failing, which must not be
    # reported as a missing branch.
    if process.returncode != NO_MATCHING_REF:
        sys.exit(
            f"Could not query {config.repo_url} for branch "
            f"{config.branch!r} (git exit {process.returncode}).\n"
            f"{process.stderr.strip()}")

    if config.branch_explicit:
        sys.exit(
            f"Branch {config.branch!r} does not exist on {config.repo_url}. "
            f"Check the name, or omit --branch to use the remote default.")

    # The default branch name only: upstream renaming it must not break
    # every install, so defer to whatever the remote calls its default.
    logger.warning(
        f"Branch {config.branch!r} not found on the remote; "
        f"using the remote default branch instead.")
    return None


def _check_reuse_matches_request(config: InstallConfig) -> None:
    """
    Reject reuse of a checkout that is not the requested source.

    Parameters
    ----------
    config : InstallConfig
        Install configuration.

    Raises
    ------
    SystemExit
        If the existing checkout's origin or branch differs from what was
        asked for, which would otherwise build source the user did not
        request while appearing to honour the arguments.
    """
    # Fails closed: an unreadable origin, an empty .git, or a git that will
    # not run all return None, and none of them prove the tree is the source
    # that was asked for.
    origin = _git_value(config.src_dir, "remote", "get-url", "origin")
    if origin != config.repo_url:
        found = origin if origin is not None else "unreadable"
        sys.exit(
            f"{config.src_dir} has origin {found}, not {config.repo_url}. "
            f"Drop --reuse-clone to replace it, or choose another --prefix.")

    if not config.branch_explicit:
        return

    # A detached HEAD reports "HEAD", which is never a branch name a user
    # asked for, so it is refused along with the unreadable cases.
    branch = _git_value(config.src_dir, "rev-parse", "--abbrev-ref", "HEAD")
    if branch != config.branch:
        found = branch if branch is not None else "unreadable"
        sys.exit(
            f"{config.src_dir} is on branch {found}, not {config.branch!r}. "
            f"Drop --reuse-clone to re-clone it, or check out the branch "
            f"yourself.")

########################################
# Clone SAD
########################################
def _tree_is_owned(tree: Path) -> bool:
    """
    Report whether a directory is a source tree this installer created.

    Parameters
    ----------
    tree : Path
        Directory to inspect.

    Returns
    -------
    bool
        True when the tree carries this installer's marker.
    """
    marker = tree / INSTALL_MARKER
    try:
        status = marker.lstat()
    except FileNotFoundError:
        return False
    return stat.S_ISREG(status.st_mode)


def _require_plain_dir(path: Path, what: str) -> bool:
    """
    Check that a path is an ordinary directory, or is not there at all.

    Parameters
    ----------
    path : Path
        Path to inspect.
    what : str
        Name for the path in any message.

    Returns
    -------
    bool
        True when the directory is there and ordinary, False when absent.

    Raises
    ------
    TransactionStateError
        If the path is a symlink or anything other than a directory.
    """
    # lstat, not is_dir: is_dir follows symlinks, and recovery must never
    # follow one out of the prefix and delete what it points at.
    try:
        status = path.lstat()
    except FileNotFoundError:
        return False

    if stat.S_ISLNK(status.st_mode):
        raise TransactionStateError(
            f"The {what} path is a symlink, which this installer never "
            f"creates:\n  {path}")

    if not stat.S_ISDIR(status.st_mode):
        raise TransactionStateError(
            f"The {what} path is not a directory:\n  {path}")

    return True


def _is_plain_file(path: Path) -> bool:
    """
    Report whether a path is a regular file without following a symlink.

    Parameters
    ----------
    path : Path
        Path to inspect.

    Returns
    -------
    bool
        True only for a regular file at the path itself.
    """
    try:
        status = path.lstat()
    except FileNotFoundError:
        return False
    return stat.S_ISREG(status.st_mode)


@dataclass(frozen = True)
class _TransactionState:
    """Validated filesystem state for an unfinished installation."""

    had_previous: bool
    has_backup:   bool
    has_source:   bool

########################################
# Transaction Record
########################################
def _write_transaction_record(config: InstallConfig, had_previous: bool) -> None:
    """
    Record what the transaction will have to undo.

    Whether a source tree existed cannot be re-derived once the transaction
    is under way: a first install and a replacement whose backup has yet to
    be made both have no backup.

    Parameters
    ----------
    config : InstallConfig
        Install configuration.
    had_previous : bool
        Whether a source tree existed when the transaction began.
    """
    record = {"version": TRANSACTION_VERSION, "had_previous": had_previous}

    staging = config.transaction_record.with_name(
        f"{config.transaction_record.name}.tmp")
    staging.write_text(json.dumps(record), encoding = "utf-8")
    os.replace(staging, config.transaction_record)


def _read_transaction_record(config: InstallConfig) -> dict | None:
    """
    Read the transaction record, if it is one this installer wrote.

    Parameters
    ----------
    config : InstallConfig
        Install configuration.

    Returns
    -------
    dict or None
        The record, or None when it is absent, unreadable, malformed, or
        of a version this installer does not know.
    """
    if not _is_plain_file(config.transaction_record):
        return None

    try:
        record = json.loads(
            config.transaction_record.read_text(encoding = "utf-8"))
    except (OSError, ValueError):
        return None

    if not isinstance(record, dict):
        return None
    if record.get("version") != TRANSACTION_VERSION:
        return None
    if not isinstance(record.get("had_previous"), bool):
        return None

    return record


def _load_transaction_state(
        config: InstallConfig) -> _TransactionState | None:
    """
    Validate and describe the active install transaction.

    Parameters
    ----------
    config : InstallConfig
        Install configuration.

    Returns
    -------
    _TransactionState or None
        Validated state, or None when no transaction exists.

    Raises
    ------
    TransactionStateError
        If any ownership proof, path type, or state transition is unsafe.
    """
    if not _require_plain_dir(config.transaction_dir, "transaction"):
        return None

    record = _read_transaction_record(config)
    if record is None:
        raise TransactionStateError(
            f"Found a directory where this installer keeps an install in "
            f"progress, but it carries no plain record this installer "
            f"recognises:\n  {config.transaction_dir}")

    _require_plain_dir(config.staging_dir, "staging")
    has_backup   = _require_plain_dir(config.backup_dir, "backup")
    has_source   = _require_plain_dir(config.src_dir, "source")
    had_previous = record["had_previous"]

    if has_backup and not had_previous:
        raise TransactionStateError(
            f"The transaction says no previous source existed, but a "
            f"backup is present:\n  {config.backup_dir}")

    if has_backup and not _tree_is_owned(config.backup_dir):
        raise TransactionStateError(
            f"Found a held-aside source tree that this installer cannot "
            f"identify as its own:\n  {config.backup_dir}")

    if has_source and not _tree_is_owned(config.src_dir):
        backup_note = (
            f"\nThe previous installation is preserved at:\n  "
            f"{config.backup_dir}" if has_backup else "")
        raise TransactionStateError(
            f"An unfinished install left a source tree this installer "
            f"cannot identify:\n  {config.src_dir}{backup_note}")

    if had_previous and not has_backup and not has_source:
        raise TransactionStateError(
            f"The transaction says a previous source existed, but neither "
            f"it nor its backup can be found:\n  {config.src_dir}\n  "
            f"{config.backup_dir}")

    return _TransactionState(
        had_previous = had_previous,
        has_backup   = has_backup,
        has_source   = has_source)

########################################
# Transaction Reconciliation
########################################
def reconcile_transaction(config: InstallConfig) -> None:
    """
    Finish or undo a transaction an earlier run did not complete.

    The transaction directory has a fixed name and carries its own record,
    so an install killed outright is discoverable rather than lost under a
    random path, and a directory that merely shares the name is never
    mistaken for one of ours.

    Parameters
    ----------
    config : InstallConfig
        Install configuration.

    Raises
    ------
    SystemExit
        If the recovery state cannot be shown to be this installer's. The
        exact paths are printed and nothing is removed.
    RollbackError
        If a validated recovery operation fails. Every relevant state path
        is reported for inspection.
    """
    try:
        state = _load_transaction_state(config)
    except TransactionStateError as error:
        sys.exit(
            f"{error}\nMove the unexpected path aside yourself, then rerun. "
            f"Nothing has been changed.")

    if state is None:
        return

    try:
        ########################################
        # A Previous Tree To Restore
        ########################################
        if state.has_backup:
            logger.warning(
                f"Recovering the installation an earlier run left: "
                f"{config.backup_dir}")
            _restore_backup(config, config.backup_dir)
            _retire_transaction(config)
            logger.info(f"Previous installation restored: {config.src_dir}")
            return

        ########################################
        # Nothing Was Ever Moved
        ########################################
        # The previous tree was still at src when the run died, so only the
        # transaction's own contents have to go.
        if state.had_previous:
            logger.warning(
                f"Discarding an unfinished install: {config.transaction_dir}")
            _retire_transaction(config)
            return

        ########################################
        # A First Install That Never Finished
        ########################################
        # There was nothing here before, so anything at src came from the run
        # that died, and is only removable if it says so itself.
        if state.has_source:
            logger.warning(
                f"Discarding an unfinished first install: {config.src_dir}")
            shutil.rmtree(config.src_dir)

        _retire_transaction(config)
    except (OSError, TransactionStateError) as error:
        raise RollbackError(
            f"Could not recover an unfinished SAD installation:\n  {error}\n"
            f"Inspect these paths before changing anything yourself:\n"
            f"  Source:      {config.src_dir}\n"
            f"  Backup:      {config.backup_dir}\n"
            f"  Transaction: {config.transaction_dir}") from error

########################################
# Backup Restoration
########################################
def _restore_backup(config: InstallConfig, backup: Path) -> None:
    """
    Put a held-aside source tree back, discarding the failed one.

    Every step is checked. The backup is the only copy of a working
    installation, so it is never removed when it cannot be put back.

    Parameters
    ----------
    config : InstallConfig
        Install configuration.
    backup : Path
        The held-aside tree.

    Raises
    ------
    OSError
        If the failed tree cannot be removed, or the backup cannot be
        renamed into place. The backup is left where it is.
    """
    if config.src_dir.exists():
        shutil.rmtree(config.src_dir)
    backup.rename(config.src_dir)

########################################
# Transaction Retirement
########################################
def _retire_transaction(config: InstallConfig) -> None:
    """
    Take the transaction out of play in one step, then clear it up.

    The rename is the commit point. Once it has happened no later run can
    read the directory as rollback state, so clearing up what is left is
    only tidying, and may fail without costing anything.

    Parameters
    ----------
    config : InstallConfig
        Install configuration.
    """
    if not _require_plain_dir(config.transaction_dir, "transaction"):
        return

    holder = Path(tempfile.mkdtemp(dir = config.prefix, prefix = CLEANUP_PREFIX))
    config.transaction_dir.rename(holder / "transaction")

    try:
        shutil.rmtree(holder)
    except OSError as error:
        # The install is already committed, so this is reported rather than
        # raised. Silence would leave an unexplained directory behind.
        logger.warning(f"Could not remove {holder}: {error}")

########################################
# Source Preparation
########################################
def prepare_source(config: InstallConfig) -> bool:
    """
    Put a SAD source tree where the build can run.

    A reused tree is built in place, as `--reuse-clone` asks. Otherwise the
    clone lands in the transaction directory, any previous tree is moved
    into the same transaction, and only then is the new tree renamed to
    its final path.

    Parameters
    ----------
    config : InstallConfig
        Install configuration.

    Returns
    -------
    bool
        Whether an existing tree is being reused.

    Raises
    ------
    SystemExit
        If the prefix is unsafe, if an existing tree is not this
        installer's to replace, or if the requested source cannot be had.
    CommandError
        If the clone returns non-zero. The previous source tree is left
        untouched in that case.

    Notes
    -----
    SAD's build bakes the absolute build directory into the binary, as an
    rpath and in the Tcl/Tk library paths. The tree therefore has to be at
    its final path before make runs, which is why the rename happens here
    and not after the build.
    """
    _guard_prefix(config)

    try:
        has_source = _require_plain_dir(config.src_dir, "source")
    except TransactionStateError as error:
        sys.exit(f"{error}\nNothing has been changed.")

    config.log_dir.mkdir(parents = True, exist_ok = True)

    # Truncated so a failure tail cannot be read from an earlier run. Ahead of
    # the reuse branch, which would otherwise keep appending across rebuilds.
    config.build_log.write_text("")
    logger.info(f"Build log: {config.build_log}")

    if config.reuse_clone and has_source and (
            config.src_dir / ".git").is_dir():
        _check_reuse_matches_request(config)
        logger.info(f"Reusing existing source tree in place: {config.src_dir}")
        return True

    # Everything that can refuse the install runs before anything is moved:
    # a mistyped branch must not cost the user a working installation.
    branch = _resolve_branch(config)
    if has_source and not _installer_owns_tree(config):
        sys.exit(
            f"{config.src_dir} already exists and was not created by this "
            f"installer. Remove it yourself, or choose another --prefix.")

    cmd = ["git", "clone", "--depth", "1"]
    if branch is not None:
        cmd += ["--branch", branch]

    ########################################
    # Open The Transaction
    ########################################
    config.transaction_dir.mkdir(parents = True, exist_ok = True)

    # An interrupted clone leaves nothing at src, so a run killed here has
    # only the transaction directory to discard.
    try:
        _write_transaction_record(config, has_source)
        run(
            cmd + [config.repo_url, str(config.staging_dir)],
            log_path        = config.build_log,
            stdin_devnull   = True)
        (config.staging_dir / INSTALL_MARKER).touch()
    except BaseException:
        _retire_transaction(config)
        raise

    ########################################
    # Move The Previous Tree Aside
    ########################################
    moved = False
    if has_source:
        config.src_dir.rename(config.backup_dir)
        moved = True
        logger.info(f"Previous source tree held aside: {config.backup_dir}")

    try:
        config.staging_dir.rename(config.src_dir)
    except BaseException:
        if moved:
            config.backup_dir.rename(config.src_dir)
        _retire_transaction(config)
        raise

    return False

########################################
# Rollback
########################################
def rollback(
        config: InstallConfig,
        cause:  BaseException) -> None:
    """
    Undo a failed install, or explain exactly what was preserved.

    What has to be undone comes from the transaction record, not from
    guesswork: a first install has no backup to put back, but it does have
    a source tree that only this run created.

    Parameters
    ----------
    config : InstallConfig
        Install configuration.
    cause : BaseException
        The failure being rolled back, named in any rollback error.

    Raises
    ------
    RollbackError
        If the previous state cannot be restored or interpreted safely. The
        preserved transaction path is reported with the original failure.
    """
    try:
        state = _load_transaction_state(config)
    except TransactionStateError as error:
        raise RollbackError(
            f"The install failed:\n  {cause}\n"
            f"Undoing it was refused because the transaction state is not "
            f"safe:\n  {error}\n"
            f"The unfinished transaction has been preserved at:\n"
            f"  {config.transaction_dir}") from cause

    # --reuse-clone opens no transaction: the tree it was told to build in
    # is the only one there is, and there is nothing to put back.
    if state is None:
        return

    try:
        if state.has_backup:
            _restore_backup(config, config.backup_dir)
        elif not state.had_previous and state.has_source:
            # Nothing was here before this run, so the failed tree goes.
            shutil.rmtree(config.src_dir)
    except OSError as error:
        raise RollbackError(
            f"The install failed:\n  {cause}\n"
            f"Undoing it also failed:\n  {error}\n"
            f"The unfinished transaction has been preserved at:\n"
            f"  {config.transaction_dir}\n"
            f"Your previous source tree, if one existed, remains at:\n"
            f"  {config.backup_dir}\n"
            f"Put it back at {config.src_dir} yourself once the cause is "
            f"clear.") from cause

    _retire_transaction(config)

